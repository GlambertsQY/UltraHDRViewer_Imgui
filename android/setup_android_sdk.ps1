# Installs the Android build toolchain used by this project into <repo>/.tools
# (JDK 17, Android SDK Platform 37, Build-Tools 37, NDK r28, CMake 3.22.1).
# Safe to re-run: already installed components are skipped.
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$repoRoot = Split-Path -Parent $PSScriptRoot
$toolsDir = Join-Path $repoRoot '.tools'
$sdkRoot  = Join-Path $toolsDir 'android-sdk'
$jdkRoot  = Join-Path $toolsDir 'jdk-17'
$dlDir    = Join-Path $toolsDir 'downloads'

New-Item -ItemType Directory -Force -Path $toolsDir, $sdkRoot, $dlDir | Out-Null

function Download-File([string]$Url, [string]$OutFile) {
    if (Test-Path $OutFile) {
        Write-Host "  [skip] $(Split-Path -Leaf $OutFile)"
        return
    }
    Write-Host "  [get ] $Url"
    Invoke-WebRequest -Uri $Url -OutFile $OutFile -UseBasicParsing
}

# ---------------------------------------------------------------- JDK 17
if (Test-Path (Join-Path $jdkRoot 'bin\java.exe')) {
    Write-Host "JDK already installed: $jdkRoot"
} else {
    Write-Host "Installing Temurin JDK 17..."
    $jdkZip = Join-Path $dlDir 'jdk17.zip'
    Download-File 'https://api.adoptium.net/v3/binary/latest/17/ga/windows/x64/jdk/hotspot/normal/eclipse?project=jdk' $jdkZip
    $tmp = Join-Path $dlDir 'jdk-extract'
    if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force }
    Expand-Archive -Path $jdkZip -DestinationPath $tmp -Force
    $inner = Get-ChildItem $tmp -Directory | Select-Object -First 1
    if (-not $inner) { throw "Unexpected JDK archive layout" }
    if (Test-Path $jdkRoot) { Remove-Item $jdkRoot -Recurse -Force }
    Move-Item $inner.FullName $jdkRoot
    Remove-Item $tmp -Recurse -Force
}
$env:JAVA_HOME = $jdkRoot
$env:PATH = (Join-Path $jdkRoot 'bin') + ';' + $env:PATH

# ---------------------------------------------------- Android cmdline-tools
$sdkManager = Join-Path $sdkRoot 'cmdline-tools\latest\bin\sdkmanager.bat'
if (Test-Path $sdkManager) {
    Write-Host "cmdline-tools already installed."
} else {
    Write-Host "Installing Android command-line tools..."
    [xml]$repo = Invoke-WebRequest -Uri 'https://dl.google.com/android/repository/repository2-3.xml' -UseBasicParsing |
        Select-Object -ExpandProperty Content
    $pkg = $repo.'sdk-repository'.remotePackage | Where-Object { $_.path -eq 'cmdline-tools;latest' }
    if (-not $pkg) { throw "cmdline-tools;latest not found in SDK repository" }
    $archive = $pkg.archives.archive | Where-Object { $_.'host-os' -eq 'windows' } | Select-Object -First 1
    if (-not $archive) { $archive = $pkg.archives.archive | Select-Object -First 1 }
    $url = 'https://dl.google.com/android/repository/' + $archive.complete.url
    $zip = Join-Path $dlDir 'commandlinetools.zip'
    Download-File $url $zip
    $tmp = Join-Path $dlDir 'cmdline-tools-extract'
    if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force }
    Expand-Archive -Path $zip -DestinationPath $tmp -Force
    New-Item -ItemType Directory -Force -Path (Join-Path $sdkRoot 'cmdline-tools') | Out-Null
    $dest = Join-Path $sdkRoot 'cmdline-tools\latest'
    if (Test-Path $dest) { Remove-Item $dest -Recurse -Force }
    Move-Item (Join-Path $tmp 'cmdline-tools') $dest
    Remove-Item $tmp -Recurse -Force
}

# ------------------------------------------------------------ SDK packages
# sdkmanager writes warnings/progress to stderr; run it out-of-process so
# PowerShell does not treat those as errors, and keep the console readable.
$ErrorActionPreference = 'Continue'
Write-Host "Accepting SDK licenses..."
$licenseLog = Join-Path $dlDir 'sdkmanager-licenses.log'
$yes = ("y`r`n" * 60)
$yes | & $sdkManager --sdk_root="$sdkRoot" --licenses *> $licenseLog

$packages = @(
    'platform-tools',
    'platforms/android-37.0',
    'build-tools/37.0.0',
    'build-tools/36.0.0',
    'ndk/28.2.13676358',
    'cmake/3.22.1'
)
foreach ($p in $packages) {
    Write-Host "Installing $p..."
    $log = Join-Path $dlDir ("sdkmanager-" + ($p -replace '[;\\/:*?"<>|]', '_') + ".log")
    $proc = Start-Process -FilePath $sdkManager -ArgumentList @("--sdk_root=$sdkRoot", $p) `
        -Wait -NoNewWindow -PassThru -RedirectStandardOutput $log -RedirectStandardError "$log.err"
    if ($proc.ExitCode -ne 0) {
        Write-Warning "Install failed for '$p' (exit $($proc.ExitCode)); see $log"
        Get-Content $log -Tail 20 -ErrorAction SilentlyContinue | ForEach-Object { Write-Host "    $_" }
        Get-Content "$log.err" -Tail 20 -ErrorAction SilentlyContinue | ForEach-Object { Write-Host "    $_" }
    } else {
        Write-Host "  ok"
    }
}
$ErrorActionPreference = 'Stop'

# --------------------------------------------------------- local.properties
$localProps = Join-Path $PSScriptRoot 'local.properties'
$sdkPath = $sdkRoot -replace '\\', '/'
@(
    "# Generated by setup_android_sdk.ps1"
    "sdk.dir=$sdkPath"
) | Set-Content -Path $localProps -Encoding ASCII

Write-Host ""
Write-Host "Done."
Write-Host "  JAVA_HOME = $jdkRoot"
Write-Host "  SDK       = $sdkRoot"
Write-Host ""
Write-Host "Build with:"
Write-Host "  `$env:JAVA_HOME='$jdkRoot'"
Write-Host "  cd android; .\gradlew.bat assembleDebug"
